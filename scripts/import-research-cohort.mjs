import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';

const [cohortPath, supplementPath, qaPath] = process.argv.slice(2);
assert.ok(cohortPath && supplementPath && qaPath, 'Provide cohort JSON, refresh JSON and cohort QA JSON paths');
const raw = await readFile(cohortPath);
const cohort = JSON.parse(raw), supplement = JSON.parse(await readFile(supplementPath)), qa = JSON.parse(await readFile(qaPath));
assert.equal(createHash('sha256').update(raw).digest('hex'), qa.json_sha256, 'Cohort checksum mismatch');
assert.equal(qa.passed, true);
assert.equal(cohort.doctors.length, cohort.summary.confirmed_unique_count);
assert.equal(new Set(cohort.doctors.map(p=>p.cohort_id)).size, cohort.doctors.length);
const sourceIds = new Set(cohort.sources.map(s=>s.source_id));
for (const p of cohort.doctors) {
  assert.ok(p.name && p.specialties.length && p.institutions.length && p.evidence.length);
  assert.equal(p.registry_verified, false);
  assert.equal(p.experience_years, null);
  assert.equal(p.dol_tier, null);
  for (const e of p.evidence) assert.ok(sourceIds.has(e.source_id) && /^https:\/\//.test(e.profile_url));
}
const payload = {
  generatedAt:cohort.generated_at, checksum:qa.json_sha256, summary:cohort.summary,
  limitations:cohort.limitations, doctors:cohort.doctors, sources:cohort.sources,
  reviewGroups:cohort.duplicate_review, excluded:cohort.excluded_or_review,
  publications:supplement.records, publicationCheckedAt:supplement.checked_at
};
await writeFile(new URL('../generated/confirmed-cohort.mjs',import.meta.url), '// Generated by scripts/import-research-cohort.mjs. Do not edit manually.\nexport const confirmedCohort = '+JSON.stringify(payload)+';\n');
console.log(`Imported ${payload.doctors.length} doctors and ${payload.publications.length} review-stage publication; no registry or social promotion.`);
